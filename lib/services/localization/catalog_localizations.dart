String _localized(
  String key,
  Locale locale,
  Map<String, Map<String, String>> catalog,
) {
  final values = catalog[key];
  return values?[locale.languageCode.toLowerCase()] ?? values?['en'] ?? key;
}

String _fromValue(
  String value,
  Locale locale,
  Map<String, Map<String, String>> catalog,
) {
  final normalized = value.trim().toLowerCase();
  if (normalized.isEmpty) return value;
  for (final entry in catalog.entries) {
    if (entry.key.toLowerCase() == normalized ||
        entry.value.values.any((name) => name.toLowerCase() == normalized)) {
      return _localized(entry.key, locale, catalog);
    }
  }
  return value;
}

String localizedService(String value, Locale locale) =>
    _fromValue(value, locale, _services);

String localizedServiceById(String sid, Locale locale) =>
    _localized(sid, locale, _services);

String localizedDiety(String value, Locale locale) =>
    _fromValue(value, locale, _deities);

String localizedDietyById(String did, Locale locale) =>
    _localized(did, locale, _deities);

String localizedBirthStar(String value, Locale locale) {
  final normalized = value.trim().toLowerCase();
  for (final entry in _stars.entries) {
    if ('${entry.key}' == normalized ||
        entry.value.values.any((name) => name.toLowerCase() == normalized)) {
      return entry.value[locale.languageCode.toLowerCase()] ??
          entry.value['en'] ??
          value;
    }
  }
  return value;
}

String localizedBirthStarById(int id, Locale locale) {
  final values = _stars[id];
  return values?[locale.languageCode.toLowerCase()] ?? values?['en'] ?? '$id';
}
